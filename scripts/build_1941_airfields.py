def entry(
    fid: str,
    name: str,
    lon: float,
    lat: float,
    category: str,
    facility_class: str,
    region: str,
    subregion: str,
    territory_1941: str,
    modern_country: str,
    control_dec_1941: str,
    alignment_dec_1941: str,
    operator_1941: str,
    surface_1941: str,
    runway_notes_1941: str,
    notes: str,
    modern_equivalent: str,
    *,
    dual_use: bool = False,
    alternate_names: list[str] | None = None,
    status_dec_1941: str = "operational",
    source_confidence: str = "high",
) -> dict[str, Any]:
    """Build a single normalized airfield record."""
    return {
        "id": fid,
        "lon": round(lon, 4),
        "lat": round(lat, 4),
        "properties": {
            "id": fid,
            "name": name,
            "alternate_names": alternate_names or [],
            "category": category,
            "dual_use": dual_use,
            "airfield_type": "land_airfield",
            "facility_class": facility_class,
            "region": region,
            "subregion": subregion,
            "territory_1941": territory_1941,
            "modern_country": modern_country,
            "control_dec_1941": control_dec_1941,
            "alignment_dec_1941": alignment_dec_1941,
            "operator_1941": operator_1941,
            "surface_1941": surface_1941,
            "runway_notes_1941": runway_notes_1941,
            "status_dec_1941": status_dec_1941,
            "notes": notes,
            "modern_equivalent": modern_equivalent,
            "source_confidence": source_confidence,
            "title": name,
            "marker-color": MARKER_COLORS[category],
            "marker-symbol": "airport",
            "marker-size": MARKER_SIZES[facility_class],
        },
    }



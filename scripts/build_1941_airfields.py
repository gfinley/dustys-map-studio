def haversine_km(lon1: float, lat1: float, lon2: float, lat2: float) -> float:
    """Compute great-circle distance in kilometers between two WGS84 points."""
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def to_feature(rec: dict[str, Any]) -> dict[str, Any]:
    """Convert internal airfield record to an RFC 7946 GeoJSON Feature."""
    return {
        "type": "Feature",
        "id": rec["id"],
        "geometry": {
            "type": "Point",
            "coordinates": [rec["lon"], rec["lat"]],
        },
        "properties": rec["properties"],
    }


def make_collection(
    records: list[dict[str, Any]],
    title: str,
    layer_filter: str,
) -> dict[str, Any]:
    """Build a GeoJSON FeatureCollection with rich top-level metadata and bbox."""
    lons = [r["lon"] for r in records]
    lats = [r["lat"] for r in records]
    region_counts = dict(sorted(Counter(r["properties"]["region"] for r in records).items()))
    cat_counts = dict(sorted(Counter(r["properties"]["category"] for r in records).items()))
    dual_count = sum(1 for r in records if r["properties"]["dual_use"])

    return {
        "type": "FeatureCollection",
        "name": title,
        "bbox": [min(lons), min(lats), max(lons), max(lats)],
        "metadata": {
            **DATASET_METADATA_BASE,
            "title": title,
            "layer_filter": layer_filter,
            "feature_count": len(records),
            "category_counts": cat_counts,
            "dual_use_count": dual_count,
            "region_counts": region_counts,
        },
        "features": [to_feature(r) for r in records],
    }


def validate_records(records: list[dict[str, Any]]) -> None:
    """Run strict geospatial and schema integrity checks before writing outputs."""
    seen_ids: set[str] = set()
    seen_names: set[str] = set()
    valid_categories = {"military", "civilian"}
    valid_regions = {
        "Philippines",
        "Malaya & Singapore",
        "Borneo",
        "Dutch East Indies",
        "French Indochina",
        "Thailand",
    }

    for rec in records:
        fid = rec["id"]
        props = rec["properties"]
        name = props["name"]
        lon, lat = rec["lon"], rec["lat"]

        assert fid not in seen_ids, f"Duplicate feature ID: {fid}"
        seen_ids.add(fid)

        assert name not in seen_names, f"Duplicate airfield name: {name}"
        seen_names.add(name)

        assert 94.0 <= lon <= 136.0, f"Longitude out of SE Asia/W Pacific bounds for {name}: {lon}"
        assert -12.0 <= lat <= 23.0, f"Latitude out of SE Asia/W Pacific bounds for {name}: {lat}"
        assert props["category"] in valid_categories, f"Invalid category for {name}: {props['category']}"
        assert props["region"] in valid_regions, f"Invalid region for {name}: {props['region']}"
        assert props["airfield_type"] == "land_airfield", f"Non-land airfield found: {name}"
        assert "seaplane base" not in name.lower(), f"Seaplane base accidentally included: {name}"

    # Flag accidental near-duplicate coordinates (< 2 km apart)
    for i in range(len(records)):
        for j in range(i + 1, len(records)):
            d = haversine_km(records[i]["lon"], records[i]["lat"], records[j]["lon"], records[j]["lat"])
            if d < 2.0:
                raise AssertionError(
                    f"Airfields suspiciously close ({d:.2f} km): "
                    f"{records[i]['properties']['name']} vs {records[j]['properties']['name']}"
                )


def main() -> None:
    validate_records(AIRFIELDS)

    military = [r for r in AIRFIELDS if r["properties"]["category"] == "military"]
    civilian = [r for r in AIRFIELDS if r["properties"]["category"] == "civilian"]
    assert len(military) + len(civilian) == len(AIRFIELDS)

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    outputs = [
        (
            OUT_DIR / "airfields_1941_se_asia_western_pacific.geojson",
            make_collection(
                AIRFIELDS,
                "1941 Southeast Asia & Western Pacific Land Airfields (Combined)",
                "all_land_airfields",
            ),
        ),
        (
            OUT_DIR / "airfields_1941_se_asia_western_pacific_military.geojson",
            make_collection(
                military,
                "1941 Southeast Asia & Western Pacific Land Airfields — Military",
                "category == 'military'",
            ),
        ),
        (
            OUT_DIR / "airfields_1941_se_asia_western_pacific_civilian.geojson",
            make_collection(
                civilian,
                "1941 Southeast Asia & Western Pacific Land Airfields — Civilian",
                "category == 'civilian'",
            ),
        ),
    ]

    for path, fc in outputs:
        path.write_text(json.dumps(fc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT_DIR)} ({len(fc['features'])} features)")

    print("\nSummary by region:")
    for region in sorted({r["properties"]["region"] for r in AIRFIELDS}):
        m_cnt = sum(1 for r in military if r["properties"]["region"] == region)
        c_cnt = sum(1 for r in civilian if r["properties"]["region"] == region)
        print(f"  - {region:20s}: {m_cnt + c_cnt:3d} total ({m_cnt:2d} military, {c_cnt:2d} civilian)")
    print(f"  TOTAL: {len(AIRFIELDS)} land airfields ({len(military)} military, {len(civilian)} civilian)")


if __name__ == "__main__":
    main()

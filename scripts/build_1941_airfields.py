"""Build and validate 1941 Southeast Asia & Western Pacific land airfield GeoJSON layers.

Produces three RFC 7946 GeoJSON FeatureCollections in ``site/data/``:
  1. ``airfields_1941_se_asia_western_pacific.geojson``          (Combined: all land airfields)
  2. ``airfields_1941_se_asia_western_pacific_military.geojson`` (Military land airfields)
  3. ``airfields_1941_se_asia_western_pacific_civilian.geojson`` (Civilian land airfields)

Historical scope:
  - Date snapshot: Late 1941 (Eve of the Pacific War, ~7-8 December 1941).
  - Geographic coverage: Philippines, British Malaya & Singapore, Borneo (Sarawak & Dutch
    Kalimantan), Dutch East Indies (Java, Sumatra, Sulawesi/Celebes, Lesser Sundas, Moluccas,
    Dutch New Guinea) + Portuguese Timor, French Indochina, and Thailand (Siam).
  - Facility scope: Land airfields only (pure seaplane bases and water anchorages excluded).
  - Partitioning: ``military`` and ``civilian`` layers form a disjoint partition of the combined
    dataset so both layers can be overlaid simultaneously without duplicate hidden points;
    dual-use facilities carry ``dual_use: true`` and full operator metadata.
"""

